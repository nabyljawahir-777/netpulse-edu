export const createDefaultPorts = (deviceType: string, deviceId: string): DevicePort[] => {
  const macGen = () => 
    '00:' + Array.from({ length: 5 }, () => Math.floor(Math.random() * 256).toString(16).padStart(2, '0')).join(':').toUpperCase();

  switch (deviceType) {
    case 'router':
      return [
        { id: `${deviceId}-g00`, name: 'GigabitEthernet0/0', type: 'gigabit', status: 'up', ipAddress: '192.168.10.1', subnetMask: '255.255.255.0', macAddress: macGen() },
        { id: `${deviceId}-g01`, name: 'GigabitEthernet0/1', type: 'gigabit', status: 'down', macAddress: macGen() },
        { id: `${deviceId}-s010`, name: 'Serial0/1/0', type: 'serial', status: 'down', macAddress: macGen() },
        { id: `${deviceId}-console`, name: 'Console', type: 'console', status: 'up', macAddress: macGen() },
      ];
    case 'multilayer_switch':
      return [
        { id: `${deviceId}-g101`, name: 'GigabitEthernet1/0/1', type: 'gigabit', status: 'up', macAddress: macGen(), mode: 'trunk' },
        { id: `${deviceId}-g102`, name: 'GigabitEthernet1/0/2', type: 'gigabit', status: 'up', macAddress: macGen(), mode: 'access', vlan: 10 },
        { id: `${deviceId}-g103`, name: 'GigabitEthernet1/0/3', type: 'gigabit', status: 'up', macAddress: macGen(), mode: 'access', vlan: 20 },
        { id: `${deviceId}-g104`, name: 'GigabitEthernet1/0/4', type: 'gigabit', status: 'down', macAddress: macGen() },
        { id: `${deviceId}-console`, name: 'Console', type: 'console', status: 'up', macAddress: macGen() },
      ];
    case 'switch':
      return [
        { id: `${deviceId}-fa01`, name: 'FastEthernet0/1', type: 'ethernet', status: 'up', macAddress: macGen(), mode: 'trunk' },
        { id: `${deviceId}-fa02`, name: 'FastEthernet0/2', type: 'ethernet', status: 'up', macAddress: macGen(), mode: 'access', vlan: 10 },
        { id: `${deviceId}-fa03`, name: 'FastEthernet0/3', type: 'ethernet', status: 'up', macAddress: macGen(), mode: 'access', vlan: 10 },
        { id: `${deviceId}-fa04`, name: 'FastEthernet0/4', type: 'ethernet', status: 'down', macAddress: macGen(), mode: 'access', vlan: 20 },
        { id: `${deviceId}-console`, name: 'Console', type: 'console', status: 'up', macAddress: macGen() },
      ];
    case 'firewall':
      return [
        { id: `${deviceId}-eth0`, name: 'Ethernet0/0 (Outside/WAN)', type: 'ethernet', status: 'up', ipAddress: '203.0.113.1', subnetMask: '255.255.255.0', macAddress: macGen() },
        { id: `${deviceId}-eth1`, name: 'Ethernet0/1 (Inside/LAN)', type: 'ethernet', status: 'up', ipAddress: '192.168.1.1', subnetMask: '255.255.255.0', macAddress: macGen() },
        { id: `${deviceId}-eth2`, name: 'Ethernet0/2 (DMZ)', type: 'ethernet', status: 'down', macAddress: macGen() },
      ];
    case 'access_point':
      return [
        { id: `${deviceId}-eth0`, name: 'GigabitEthernet0 (PoE Uplink)', type: 'gigabit', status: 'up', macAddress: macGen() },
        { id: `${deviceId}-wlan`, name: 'Radio2.4GHz / 5GHz SSID', type: 'ethernet', status: 'up', macAddress: macGen() },
      ];
    case 'server':
      return [
        { id: `${deviceId}-nic0`, name: 'FastEthernet0', type: 'ethernet', status: 'up', ipAddress: '192.168.10.10', subnetMask: '255.255.255.0', macAddress: macGen() },
      ];
    case 'printer':
      return [
        { id: `${deviceId}-nic0`, name: 'FastEthernet0', type: 'ethernet', status: 'up', ipAddress: '192.168.10.50', subnetMask: '255.255.255.0', macAddress: macGen() },
      ];
    case 'laptop':
      return [
        { id: `${deviceId}-nic0`, name: 'FastEthernet0', type: 'ethernet', status: 'up', ipAddress: '0.0.0.0', subnetMask: '0.0.0.0', macAddress: macGen() },
        { id: `${deviceId}-wlan0`, name: 'Wireless0', type: 'ethernet', status: 'down', macAddress: macGen() },
      ];
    case 'smartphone':
      return [
        { id: `${deviceId}-wlan0`, name: 'Wireless0', type: 'ethernet', status: 'up', ipAddress: '0.0.0.0', subnetMask: '0.0.0.0', macAddress: macGen() },
      ];
    case 'pc':
    default:
      return [
        { id: `${deviceId}-nic0`, name: 'FastEthernet0', type: 'ethernet', status: 'up', ipAddress: '0.0.0.0', subnetMask: '0.0.0.0', macAddress: macGen() },
        { id: `${deviceId}-rs232`, name: 'RS 232 (Serial COM)', type: 'console', status: 'up', macAddress: macGen() },
      ];
  }
};

